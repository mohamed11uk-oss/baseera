"""Evaluate the risk engine on data/testset/labeled.csv (offline) and write docs/eval.md.

Predicted fraudulent = risk >= threshold. Sweeps thresholds, prints confusion matrix, precision/recall/F1/FPR,
latency, per-signal ablation, and every FP/FN with the signals that caused it. No numbers are hand-written.
"""
from __future__ import annotations

import csv
import os
import statistics
import sys
import time
from pathlib import Path

os.environ["BASEERA_MODE"] = "offline"
os.environ["SOURCE_FEEDS"] = "off"  # measure the engine, not whatever feed DB was refreshed locally
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from baseera.analyze import Analyzer  # noqa: E402
from baseera.config import Settings  # noqa: E402
from baseera.scoring import load_weights, score  # noqa: E402


def load():
    rows = []
    with open(ROOT / "data/testset/labeled.csv", encoding="utf-8") as f:
        for r in csv.DictReader(ln for ln in f if not ln.startswith("#")):
            rows.append(r)
    return rows


def metrics(pairs, t):
    tp = sum(1 for y, s in pairs if y == 1 and s >= t)
    fp = sum(1 for y, s in pairs if y == 0 and s >= t)
    fn = sum(1 for y, s in pairs if y == 1 and s < t)
    tn = sum(1 for y, s in pairs if y == 0 and s < t)
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * p * r / (p + r) if p + r else 0.0
    fpr = fp / (fp + tn) if fp + tn else 0.0
    return dict(tp=tp, fp=fp, fn=fn, tn=tn, precision=p, recall=r, f1=f1, fpr=fpr)


def main():
    s = Settings()
    s.mode = "offline"
    an = Analyzer(settings=s, feed=set(), feeds=None, gsb=None)  # feed disabled: measure the engine, not the synthetic blocklist
    w = load_weights()
    T = w["thresholds"]["medium"]
    rows = load()
    results, lat = [], []
    for r in rows:
        t0 = time.perf_counter()
        v = an.analyze_url(r["url"])
        lat.append((time.perf_counter() - t0) * 1000)
        results.append((r, v))
    pairs = [(int(r["label"]), v.risk) for r, v in results]
    invented = sum(1 for r in rows if r["label"] == "0" and any(w in r["note"].lower() for w in ("invented", "illustrative")))
    out = ["# Baseera evaluation (generated by `make eval`, do not edit by hand)", "",
           f"- Test set: `data/testset/labeled.csv` — {len(rows)} URLs ({sum(p[0] for p in pairs)} fraudulent, "
           f"{len(rows) - sum(p[0] for p in pairs)} benign).",
           "- **The fraudulent examples are SYNTHETIC** (invented look-alikes written by the team). Benign examples are real public "
           f"sites, except {invented} rows whose note says invented/illustrative (benign URL shapes such as a shared-platform "
           "sub-domain or an illustrative path on an official domain). These numbers show the engine behaves as designed; they are NOT a measurement of real-world accuracy.",
           "- Mode: offline (no RDAP/TLS/redirect lookups, synthetic blocklist disabled).",
           f"- Decision rule: fraudulent if risk >= {T} (the 'medium' threshold in data/weights.yaml).", ""]
    m = metrics(pairs, T)
    out += ["## Confusion matrix at the current threshold", "", "| | predicted fraud | predicted benign |", "|---|---|---|",
            f"| actual fraud | TP {m['tp']} | FN {m['fn']} |", f"| actual benign | FP {m['fp']} | TN {m['tn']} |", "",
            f"Precision **{m['precision']:.2f}**, Recall **{m['recall']:.2f}**, F1 **{m['f1']:.2f}**, FPR **{m['fpr']:.2f}**", "",
            f"Latency per URL (offline): median {statistics.median(lat):.2f} ms, p95 {sorted(lat)[int(0.95 * (len(lat) - 1))]:.2f} ms", "",
            "## Threshold sweep", "", "| threshold | precision | recall | F1 | FPR |", "|---|---|---|---|---|"]
    for t in range(15, 80, 5):
        mm = metrics(pairs, t)
        out.append(f"| {t} | {mm['precision']:.2f} | {mm['recall']:.2f} | {mm['f1']:.2f} | {mm['fpr']:.2f} |")
    out += ["", "## Ablation (remove one signal, threshold fixed)", "", "| signal removed | precision | recall | F1 | FPR |", "|---|---|---|---|---|"]
    for sig in sorted(w["weights"]):
        ps = []
        for r, v in results:
            sigs = [x.model_copy() for x in v.signals]
            official = bool(v.matched_entity and v.matched_entity.get("relation") == "official")
            risk, _ = score(sigs, official=official, disabled={sig})
            ps.append((int(r["label"]), risk))
        mm = metrics(ps, T)
        if mm != m:
            out.append(f"| {sig} | {mm['precision']:.2f} | {mm['recall']:.2f} | {mm['f1']:.2f} | {mm['fpr']:.2f} |")
    out += ["", "(signals whose removal changes nothing on this set are omitted)", "", "## Errors", ""]
    errs = [(r, v) for r, v in results if (int(r["label"]) == 1) != (v.risk >= T)]
    if not errs:
        out.append("None.")
    for r, v in errs:
        kind = "FALSE NEGATIVE" if r["label"] == "1" else "FALSE POSITIVE"
        sig = ", ".join(f"{x.id}={x.contribution}" for x in v.signals if x.contribution) or "no signals"
        out.append(f"- **{kind}** `{r['url']}` risk {v.risk} ({r['note']}) — {sig}")
    out += ["", "## Per-group detail", "", "| group | n | flagged |", "|---|---|---|"]
    groups = {}
    for r, v in results:
        g = groups.setdefault(r["group"], [0, 0])
        g[0] += 1
        g[1] += v.risk >= T
    for g, (n, f) in groups.items():
        out.append(f"| {g} | {n} | {f} |")
    text = "\n".join(out) + "\n"
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/eval.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
