def eval_metrics() -> dict:
    p = ROOT / "docs" / "eval.md"
    t = p.read_text(encoding="utf-8") if p.exists() else ""
    m = re.search(r"Precision \*\*([\d.]+)\*\*, Recall \*\*([\d.]+)\*\*, F1 \*\*([\d.]+)\*\*, FPR \*\*([\d.]+)\*\*", t)
    n = re.search(r"— (\d+) URLs \((\d+) fraudulent, (\d+) benign\)", t)
    lat = re.search(r"median ([\d.]+) ms, p95 ([\d.]+) ms", t)
    return {"p": m and m.group(1), "r": m and m.group(2), "f1": m and m.group(3), "fpr": m and m.group(4),
            "n": n and n.group(1), "pos": n and n.group(2), "neg": n and n.group(3), "med": lat and lat.group(1)}


def box(slide, x, y, w, h, fill=None, line=None, shape=MSO_SHAPE.RECTANGLE):
    s = slide.shapes.add_shape(shape, x, y, w, h)
    if fill is None:
        s.fill.background()
    else:
        s.fill.solid()
        s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
    s.shadow.inherit = False
    return s


def text(slide, x, y, w, h, lines, size=18, color=INK, bold=False, align=PP_ALIGN.LEFT, rtl=False):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    for i, ln in enumerate(lines if isinstance(lines, list) else [lines]):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        if isinstance(ln, tuple):
            ln, sz, col, b = ln
        else:
            sz, col, b = size, color, bold
        p.text = ln
        p.alignment = PP_ALIGN.RIGHT if rtl else align
        if rtl:
            p._pPr.set("rtl", "1") if p._pPr is not None else p._p.get_or_add_pPr().set("rtl", "1")
        p.space_after = Pt(6)
        for r in p.runs:
            r.font.size, r.font.color.rgb, r.font.bold, r.font.name = Pt(sz), col, b, FONT
    return tb


