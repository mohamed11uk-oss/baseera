def notes(slide, s):
    slide.notes_slide.notes_text_frame.text = s


def image(slide, name, x, y, w=None, h=None):
    p = SHOTS / name
    if p.exists():  # fit inside a 6.7M x 5.5M EMU frame, keep aspect ratio
        from PIL import Image as _I
        iw, ih = _I.open(p).size
        fw, fh = 6700000, 5500000
        sc = min(fw / iw, fh / ih)
        return slide.shapes.add_picture(str(p), x, y, Emu(int(iw * sc)), Emu(int(ih * sc)))
    box(slide, x, y, w or Emu(5000000), h or Emu(3000000), LIGHT, MUTED)
    text(slide, x, y, w or Emu(5000000), Emu(500000), f"[screenshot missing: {name}]", 14, MUTED)


def bullets(slide, x, y, w, h, items, size=18):
    return text(slide, x, y, w, h, ["• " + i for i in items], size)


